from PyQt6.QtCore import Qt, pyqtSignal
from PyQt6.QtWidgets import QHBoxLayout, QPlainTextEdit, QVBoxLayout, QWidget
from ..components import Card, Page, ResponsiveRow, TextCard, Toggle, button, combo, icon_button, label
from ..voice_orb import VoiceOrb, TITLES, MIC_TITLES


class VoicePage(Page):
    action_requested = pyqtSignal()
    stop_requested = pyqtSignal()
    mute_requested = pyqtSignal()
    compact_requested = pyqtSignal()
    refresh_requested = pyqtSignal()

    def __init__(self):
        super().__init__('Голос', 'Нажмите микрофон и скажите, что нужно сделать')
        compact = button('Персонаж на рабочем столе', 'monitor')
        compact.clicked.connect(self.compact_requested)
        self.header.addWidget(compact)
        record = Card(margins=20)
        record.body.setSpacing(8)
        self.mascot = self.action_button = VoiceOrb(250)
        self.action_button.clicked.connect(self.action_requested)
        record.body.addWidget(self.mascot, alignment=Qt.AlignmentFlag.AlignHCenter)
        self.title = label('Готов', 'h2', True)
        self.operation = label('Нажмите, чтобы начать · Пробел / Enter при фокусе', 'secondary', True)
        self._operation_message = self.operation.text()
        self.response_status = label('Ответ: готов', 'muted', True)
        self.input_level = label('Входной уровень: 0%', 'muted', True)
        record.body.addWidget(self.input_level)
        record.body.addWidget(self.title)
        record.body.addWidget(self.response_status)
        record.body.addWidget(self.operation)
        row = QHBoxLayout()
        row.addStretch()
        self.stop_button = button('Остановить', 'stop')
        self.stop_button.setToolTip('Отменить задачу, выделение области и всю очередь речи')
        self.stop_button.clicked.connect(self.stop_requested)
        self.mute_button = button('Отключить микрофон', 'mic')
        self.mute_button.setToolTip('Отключить голосовой ввод и активацию. Озвучка управляется отдельно.')
        self.mute_button.clicked.connect(self.mute_requested)
        self.stop_button.hide()
        self.mute_button.hide()
        row.addStretch()
        record.body.addLayout(row)
        self.body.addWidget(record)
        self.text_button = button('Команда и ответ', 'message')
        self.text_button.setCheckable(True)
        self.body.addWidget(self.text_button)
        output = QWidget()
        layout = QVBoxLayout(output)
        layout.setContentsMargins(0, 0, 0, 0)
        self.recognized = TextCard('Вы сказали', 'Распознанная команда', 'user')
        self.answer = TextCard('Ответ Eidos', 'Ответ появится здесь', 'eidos')
        for panel in (self.recognized, self.answer):
            panel.text.setMinimumHeight(60)
            panel.text.setMaximumHeight(110)
        layout.addWidget(ResponsiveRow([self.recognized, self.answer], threshold=600))
        output.hide()
        self.text_button.toggled.connect(output.setVisible)
        self.body.addWidget(output)
        self.recognized.text.textChanged.connect(lambda: self.text_button.setChecked(True))
        self.answer.text.textChanged.connect(lambda: self.text_button.setChecked(True))
        self.settings_button = button('Настройки и журнал', 'settings')
        self.settings_button.setCheckable(True)
        self.body.addWidget(self.settings_button)
        settings = self.settings_panel = Card(margins=14)
        self.microphone = combo()
        self.microphone.setAccessibleName('Микрофон для записи')
        self.refresh_button = icon_button('refresh', 'Обновить список микрофонов')
        self.refresh_button.clicked.connect(self.refresh_requested)
        settings.body.addWidget(ResponsiveRow([self.microphone, self.refresh_button], threshold=450))
        self.speak = Toggle('Озвучивать ответы')
        settings.body.addWidget(self.speak)
        settings.body.addWidget(label('Примеры: «Открой YouTube», «Сделай звук потише», «Переведи область экрана».', 'muted'))
        self.details_button = button('Журнал событий', 'list')
        self.details_button.setCheckable(True)
        self.journal = QPlainTextEdit()
        self.journal.setReadOnly(True)
        self.journal.setMaximumBlockCount(100)
        self.journal.setFixedHeight(125)
        self.journal.setAccessibleName('Журнал событий')
        self.journal.hide()
        self.details_button.toggled.connect(self.journal.setVisible)
        settings.body.addWidget(self.details_button)
        settings.body.addWidget(self.journal)
        settings.hide()
        self.settings_button.toggled.connect(settings.setVisible)
        self.body.addWidget(settings)
        self.body.addStretch()

    def show_state(self, state, message):
        visual = {'idle': 'ready', 'starting': 'listening', 'recording': 'listening',
                  'playing': 'speaking', 'paused': 'paused', 'error': 'error'}.get(state, 'thinking')
        self.title.setText(TITLES[visual])
        self.set_operation(message)
        self.mascot.set_state(visual)

    def set_operation(self, message):
        self._operation_message = message
        self.operation.setText(self.mascot.microphone_error or message)

    def set_microphone(self, state, error=''):
        self.mascot.set_microphone(state, error)
        self.title.setText(MIC_TITLES[state])
        self.title.setToolTip(error)
        self.operation.setText(error or self._operation_message)
